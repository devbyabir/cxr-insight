"""Audit and clean the legacy synthetic report CSV (img_path, instructions, reports).

The legacy file is *not* usable for patient-grouped training: its image
filenames carry no verified patient identity and its reports are synthetic,
generated by a base (not fine-tuned) VLM. This tool makes those facts
measurable and produces a deduplicated, explicitly labelled copy for audit.
"""
import argparse
import csv
import json
import re
from collections import Counter
from pathlib import Path

from .data import digest
from .inference import parse_report

LEGACY_COLUMNS = ("img_path", "instructions", "reports")
LEGACY_GENERATOR = "unsloth/Llama-3.2-11B-Vision-Instruct (base model, prompted; not fine-tuned)"
_FINDING = re.compile(r"the detected disease is\s+([A-Za-z_ ]+?)\.", re.IGNORECASE)
_ROLE = re.compile(r"^\s*user\s*assistant\s*", re.IGNORECASE)


def read_legacy(path):
    with Path(path).open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != LEGACY_COLUMNS:
            raise ValueError(f"Expected columns {LEGACY_COLUMNS}, got {reader.fieldnames}")
        return [dict(row) for row in reader]


def clean_legacy(rows):
    seen, unique = set(), []
    for row in rows:
        key = tuple(row[c] for c in LEGACY_COLUMNS)
        if key not in seen:
            seen.add(key)
            unique.append(row)
    cleaned, counts = [], Counter()
    for row in unique:
        match = _FINDING.search(row["instructions"])
        if not match:
            raise ValueError(f"No finding label in instruction for {row['img_path']}")
        parts = Path(row["img_path"].replace("\\", "/")).parts
        raw = row["reports"]
        parsed = parse_report(raw)
        counts["role_prefix"] += bool(_ROLE.match(raw))
        counts["example_leak"] += bool(parsed.leaked_example_phrases)
        counts["complete_sections"] += parsed.complete
        counts["label_mismatch"] += parts[-2] != match.group(1).strip()
        cleaned.append({
            "image_path": "/".join(parts[-2:]),
            "folder": parts[-2],
            "prompt_label": match.group(1).strip(),
            "report": _ROLE.sub("", raw, count=1).strip(),
            "report_source": "synthetic",
            "generator": LEGACY_GENERATOR,
            "example_leak": ";".join(parsed.leaked_example_phrases),
            "missing_sections": ";".join(parsed.missing),
        })
    audit = {
        "input_rows": len(rows),
        "unique_rows": len(unique),
        "exact_duplicate_rows": len(rows) - len(unique),
        "unique_image_paths": len({r["img_path"] for r in unique}),
        "rows_with_role_prefix": counts["role_prefix"],
        "rows_with_example_leak": counts["example_leak"],
        "rows_with_all_sections": counts["complete_sections"],
        "rows_where_prompt_label_differs_from_folder": counts["label_mismatch"],
        "per_folder": dict(sorted(Counter(r["folder"] for r in cleaned).items())),
        "patient_ids_available": False,
        "report_source": "synthetic",
    }
    return cleaned, audit


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    cleaned, audit = clean_legacy(read_legacy(args.csv))
    audit["input_sha256"] = digest(args.csv)
    args.output.mkdir(parents=True, exist_ok=False)
    with (args.output / "legacy_cleaned.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(cleaned[0]))
        writer.writeheader()
        writer.writerows(cleaned)
    (args.output / "legacy_audit.json").write_text(json.dumps(audit, indent=2), encoding="utf-8")
    print(json.dumps(audit, indent=2))


if __name__ == "__main__":
    main()
